import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from 'react';
import {useLocation, useNavigation, type Location} from 'react-router';

const LIST_FILTER_KEYS = ['size', 'fit', 'sort'] as const;

type GlobalLoadingContextValue = {
  setPageLoading: (active: boolean) => void;
};

const GlobalLoadingContext = createContext<GlobalLoadingContextValue | null>(
  null,
);

export function usePageLoading(active: boolean) {
  const context = useContext(GlobalLoadingContext);

  if (!context) {
    throw new Error('usePageLoading must be used within GlobalLoadingProvider');
  }

  useEffect(() => {
    context.setPageLoading(active);
    return () => context.setPageLoading(false);
  }, [active, context]);
}

export function GlobalLoadingProvider({children}: {children: ReactNode}) {
  const location = useLocation();
  const navigation = useNavigation();
  const [pageLoading, setPageLoadingState] = useState(false);
  const setPageLoading = useCallback((active: boolean) => {
    setPageLoadingState(active);
  }, []);
  const value = useMemo(() => ({setPageLoading}), [setPageLoading]);
  const isLoading = pageLoading || shouldShowRouteLoading(navigation, location);

  return (
    <GlobalLoadingContext.Provider value={value}>
      {children}
      {isLoading ? <GlobalLoadingOverlay /> : null}
    </GlobalLoadingContext.Provider>
  );
}

