function shouldShowRouteLoading(
  navigation: ReturnType<typeof useNavigation>,
  location: Location,
) {
  if (navigation.state !== 'loading' || !navigation.location) return false;
  if (navigation.location.pathname !== location.pathname) return true;

  return isMainListQueryChange(
    location.pathname,
    location.search,
    navigation.location.search,
  );
}

function isMainListQueryChange(
  pathname: string,
  currentSearch: string,
  nextSearch: string,
) {
  const currentParams = new URLSearchParams(currentSearch);
  const nextParams = new URLSearchParams(nextSearch);

  if (pathname.startsWith('/collections/')) {
    return LIST_FILTER_KEYS.some(
      (key) =>
        currentParams.getAll(key).join('\0') !==
        nextParams.getAll(key).join('\0'),
    );
  }

  if (pathname === '/search') {
    return currentParams.get('q') !== nextParams.get('q');
  }

  return false;
}
